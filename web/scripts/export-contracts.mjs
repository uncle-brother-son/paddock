// Writes the /api/v1 contract types to the staff app, so its backend functions are type-checked
// against the Worker. Types only: the staff app has no zod.
//
//   npm run export:contracts   writes backend/paddock/shared/workerContracts.ts
//   npm run check:contracts    fails if that file is out of date
//
// The staff app's checkout is expected beside this repo; set RETOOL_APP_DIR if it isn't.
import { createHash } from 'node:crypto'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const contractsDir = path.join(webDir, 'contracts')
const entry = path.join(contractsDir, 'index.ts')
const retoolAppDir = process.env.RETOOL_APP_DIR ?? path.resolve(webDir, '../../paddock-retool-app')
const target = path.join(retoolAppDir, 'backend/paddock/shared/workerContracts.ts')

function sourceHash() {
  const hash = createHash('sha256')
  const files = readdirSync(contractsDir)
    .filter((name) => name.endsWith('.ts') && !name.endsWith('.test.ts'))
    .sort()
  for (const name of files) {
    hash.update(name)
    hash.update(readFileSync(path.join(contractsDir, name)))
  }
  return hash.digest('hex')
}

const printFlags =
  ts.TypeFormatFlags.NoTruncation |
  ts.TypeFormatFlags.InTypeAlias |
  ts.TypeFormatFlags.UseSingleQuotesForStringLiteralType

function loadChecker() {
  const configFile = ts.readConfigFile(path.join(webDir, 'tsconfig.json'), ts.sys.readFile)
  const { options } = ts.parseJsonConfigFileContent(configFile.config, ts.sys, webDir)
  const program = ts.createProgram([entry], { ...options, noEmit: true, incremental: false, tsBuildInfoFile: undefined })
  const problems = ts.getPreEmitDiagnostics(program).filter((d) => d.file?.fileName.startsWith(contractsDir))
  if (problems.length > 0) {
    throw new Error(ts.formatDiagnostics(problems, ts.createCompilerHost(options)))
  }
  return { checker: program.getTypeChecker(), sourceFile: program.getSourceFile(entry) }
}

/** Every exported type alias, with zod's inferred types spelled out in full. */
function printExportedTypes() {
  const { checker, sourceFile } = loadChecker()
  const moduleSymbol = checker.getSymbolAtLocation(sourceFile)
  const printed = []
  for (const exported of checker.getExportsOfModule(moduleSymbol)) {
    const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported
    if (!(symbol.flags & ts.SymbolFlags.TypeAlias)) continue
    const declaration = symbol.declarations?.find(ts.isTypeAliasDeclaration)
    const typeParameters = declaration?.typeParameters?.map((p) => p.name.text) ?? []
    const generics = typeParameters.length > 0 ? `<${typeParameters.join(', ')}>` : ''
    const text = checker.typeToString(checker.getDeclaredTypeOfSymbol(symbol), undefined, printFlags)
    printed.push({ name: exported.name, text: `export type ${exported.name}${generics} = ${text}` })
  }
  return printed.sort((a, b) => a.name.localeCompare(b.name)).map((entry) => entry.text)
}

function render() {
  const header = [
    '// GENERATED by `npm run export:contracts` in ~/Documents/Code/paddock/web. DO NOT EDIT.',
    '// Change the zod schemas in web/contracts/ and run it again.',
    `// Source hash: ${sourceHash()}`,
  ]
  return `${[...header, '', ...printExportedTypes().flatMap((line) => [line, ''])].join('\n').trimEnd()}\n`
}

const generated = render()

if (process.argv.includes('--check')) {
  if (!existsSync(target)) {
    console.error(`check:contracts: ${target} does not exist. Run npm run export:contracts.`)
    process.exit(1)
  }
  if (readFileSync(target, 'utf8') !== generated) {
    console.error(`check:contracts: ${target} is out of date. Run npm run export:contracts.`)
    process.exit(1)
  }
  console.log('check:contracts: workerContracts.ts is up to date.')
} else {
  if (!existsSync(path.dirname(target))) {
    console.error(`export:contracts: ${path.dirname(target)} not found. Set RETOOL_APP_DIR to the staff app's checkout.`)
    process.exit(1)
  }
  writeFileSync(target, generated)
  console.log(`export:contracts: wrote ${target}`)
}
