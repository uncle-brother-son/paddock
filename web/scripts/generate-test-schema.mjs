// Builds the test schema from a snapshot of the live database's catalog, so tests run against the
// real foreign keys, triggers and functions. Reads no data. How to refresh the snapshot is in
// server/rules/testing/README.md.
//
//   npm run schema:test           writes server/rules/testing/live-schema.sql
//   npm run schema:test -- --check   fails if that file is out of date
//   npm run schema:test -- --from <file>   takes a new snapshot first (the query's raw output)
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const snapshotFile = path.join(webDir, 'server/rules/testing/live-catalog.json')
const schemaFile = path.join(webDir, 'server/rules/testing/live-schema.sql')

/** Accepts the catalog itself, the query's rows, or a tool's wrapped answer around those rows. */
function readCatalog(text) {
  const parsed = JSON.parse(text)
  if (parsed.tables) return parsed
  if (Array.isArray(parsed)) return parsed[0].catalog
  const wrapped = String(parsed.result ?? '')
  const start = wrapped.indexOf('[{"catalog"')
  const end = wrapped.lastIndexOf('}]') + 2
  if (start < 0) throw new Error('No catalog found in that file.')
  return JSON.parse(wrapped.slice(start, end))[0].catalog
}

// Live extensions the schema needs. The others (pg_cron, vault, pg_stat_statements) are Supabase's
// own, and nothing the tests run calls them.
const NEEDED_EXTENSIONS = ['btree_gist', 'pgcrypto', 'uuid-ossp']

function columnSql(column) {
  const parts = [`  ${column.name} ${column.type}`]
  if (column.default !== null) parts.push(`DEFAULT ${column.default}`)
  if (column.notNull) parts.push('NOT NULL')
  return parts.join(' ')
}

/** Views in an order where each one comes after the views it reads. */
function orderViews(views, dependencies) {
  const uses = (name) => (dependencies ?? []).filter((d) => d.view === name).map((d) => d.uses)
  const done = []
  const visit = (view) => {
    if (done.includes(view)) return
    for (const name of uses(view.name)) {
      const used = views.find((v) => v.name === name)
      if (used) visit(used)
    }
    done.push(view)
  }
  views.forEach(visit)
  return done
}

export function buildSchema(catalog) {
  const missing = NEEDED_EXTENSIONS.filter((name) => !catalog.extensions.some((e) => e.name === name))
  if (missing.length > 0) throw new Error(`The catalog has no ${missing.join(', ')} extension.`)
  for (const table of catalog.tables) {
    for (const column of table.columns) {
      if (column.generated || column.identity) throw new Error(`${table.name}.${column.name}: generated columns aren't handled.`)
    }
  }

  const constraint = (k) => `ALTER TABLE public.${k.table} ADD CONSTRAINT ${k.name} ${k.definition};`
  const notForeign = catalog.constraints.filter((k) => k.type !== 'f')
  const foreign = catalog.constraints.filter((k) => k.type === 'f')
  const statement = (text) => (text.trim().endsWith(';') ? text.trim() : `${text.trim()};`)

  return [
    `-- GENERATED by scripts/generate-test-schema.mjs from live-catalog.json. Do not edit.`,
    `-- Live Postgres ${catalog.postgres}. The extensions are created by the test set-up.`,
    `-- auth.users is a stand-in: only customers.auth_user_id points at it.`,
    ``,
    `SET check_function_bodies = off;`,
    `CREATE SCHEMA IF NOT EXISTS auth;`,
    `CREATE TABLE auth.users (id uuid PRIMARY KEY);`,
    ``,
    `-- Tables`,
    ...catalog.tables.map((t) => `CREATE TABLE public.${t.name} (\n${t.columns.map(columnSql).join(',\n')}\n);\n`),
    `-- Functions`,
    ...catalog.functions.map((f) => `${statement(f.definition)}\n`),
    `-- Primary keys, unique, check and exclusion constraints (a view's GROUP BY can rely on a primary key)`,
    ...notForeign.map(constraint),
    ``,
    `-- Views`,
    ...orderViews(catalog.views, catalog.viewDependencies).map((v) => `CREATE VIEW public.${v.name} AS\n${statement(v.definition)}\n`),
    `-- Foreign keys`,
    ...foreign.map(constraint),
    ``,
    `-- Indexes`,
    ...catalog.indexes.map((i) => statement(i.definition)),
    ``,
    `-- Triggers`,
    ...catalog.triggers.map((t) => statement(t.definition)),
    ``,
    `RESET check_function_bodies;`,
    ``,
  ].join('\n')
}

const args = process.argv.slice(2)
const from = args.includes('--from') ? args[args.indexOf('--from') + 1] : null
if (from) {
  const catalog = readCatalog(readFileSync(from, 'utf8'))
  writeFileSync(snapshotFile, `${JSON.stringify(catalog, null, 1)}\n`)
}
const schema = buildSchema(readCatalog(readFileSync(snapshotFile, 'utf8')))
if (args.includes('--check')) {
  if (readFileSync(schemaFile, 'utf8') !== schema) {
    console.error('live-schema.sql is out of date: run npm run schema:test')
    process.exit(1)
  }
  console.log('live-schema.sql is up to date.')
} else {
  writeFileSync(schemaFile, schema)
  console.log(`Wrote ${path.relative(webDir, schemaFile)}`)
}
